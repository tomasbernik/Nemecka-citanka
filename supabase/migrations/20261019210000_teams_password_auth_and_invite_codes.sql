create or replace function public.app_create_team(target_name text)
returns setof public.app_teams
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  owner_id text := public.app_current_profile_id();
  created_team public.app_teams%rowtype;
begin
  if auth.uid() is null or not public.app_has_teacher_license() then
    raise exception 'teacher_license_required';
  end if;
  if char_length(trim(coalesce(target_name, ''))) not between 1 and 80 then
    raise exception 'invalid_team_name';
  end if;

  insert into public.app_teams (name, owner_profile_id)
  values (trim(target_name), owner_id)
  returning * into created_team;

  insert into public.app_team_memberships (team_id, profile_id)
  values (created_team.id, owner_id)
  on conflict (team_id, profile_id) do nothing;

  return next created_team;
end;
$$;

