create or replace function public.app_can_access_profile(target_profile_id text)
returns boolean
language sql
stable
security definer
set search_path = public, auth
as $$
  select public.app_is_publisher()
    or exists (
      select 1
      from public.app_profiles profile
      where profile.id = target_profile_id
        and (profile.auth_user_id = auth.uid() or profile.owner_auth_user_id = auth.uid())
