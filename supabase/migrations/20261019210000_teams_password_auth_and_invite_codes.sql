create or replace function public.app_set_article_assignment(
  target_team_id uuid,
  target_profile_id text,
  target_article_id text,
  target_assigned boolean
)
returns boolean
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  cleaned_assignments jsonb;
  article_title_value text;
  teacher_profile_id text := public.app_current_profile_id();
begin
  if not public.app_can_manage_team(target_team_id) then
    raise exception 'team_access_denied';
  end if;
  if not public.app_is_team_member(target_team_id, target_profile_id) then
    raise exception 'profile_not_in_team';
  end if;
  select title into article_title_value
  from public.app_articles
  where id = target_article_id and team_id = target_team_id;
  if article_title_value is null then
    raise exception 'article_not_in_team';
  end if;

  insert into public.app_profile_data (profile_id, data, updated_at)
  values (target_profile_id, '{}'::jsonb, now())
  on conflict (profile_id) do nothing;

  select coalesce(jsonb_agg(item), '[]'::jsonb)
  into cleaned_assignments
  from jsonb_array_elements(
    coalesce((select data -> 'assignments' from public.app_profile_data where profile_id = target_profile_id), '[]'::jsonb)
  ) item
  where item ->> 'articleId' is distinct from target_article_id;

  if target_assigned then
    cleaned_assignments := cleaned_assignments || jsonb_build_array(jsonb_build_object(
      'articleId', target_article_id,
      'articleTitle', article_title_value,
      'teacherId', teacher_profile_id,
      'teamId', target_team_id,
      'assignedAt', now()
    ));
  end if;

  update public.app_profile_data
  set data = jsonb_set(data, '{assignments}', cleaned_assignments, true),
      updated_at = now()
  where profile_id = target_profile_id;
  return true;
end;
$$;

create or replace function public.app_hash_team_invite_code(raw_code text)
returns text
language sql
immutable
security definer
set search_path = public, extensions
as $$
  select encode(digest(regexp_replace(upper(coalesce(raw_code, '')), '[^A-Z2-9]', '', 'g'), 'sha256'), 'hex');
$$;

create or replace function public.app_create_team_invite(target_team_id uuid)
returns table (invite_code text, team_id uuid, team_name text, expires_at timestamptz)
language plpgsql
security definer
set search_path = public, auth, extensions
as $$
declare
  alphabet constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  random_bytes bytea;
  raw_code text;
  code_hash_value text;
  team_label text;
  expiration timestamptz := now() + interval '1 hour';
  attempt integer;
begin
  if not public.app_can_manage_team(target_team_id) then
    raise exception 'team_access_denied';
  end if;

  select name into team_label from public.app_teams where id = target_team_id;
  update public.app_team_invites
  set revoked_at = now()
  where app_team_invites.team_id = target_team_id and revoked_at is null;

  for attempt in 1..10 loop
    random_bytes := gen_random_bytes(8);
    raw_code := '';
    for i in 0..7 loop
      raw_code := raw_code || substr(alphabet, (get_byte(random_bytes, i) % length(alphabet)) + 1, 1);
    end loop;
    raw_code := substr(raw_code, 1, 4) || '-' || substr(raw_code, 5, 4);
    code_hash_value := public.app_hash_team_invite_code(raw_code);
    begin
      insert into public.app_team_invites (team_id, code_hash, created_by, expires_at)
      values (target_team_id, code_hash_value, auth.uid(), expiration);
      return query select raw_code, target_team_id, team_label, expiration;
      return;
    exception when unique_violation then
      null;
    end;
  end loop;
  raise exception 'invite_generation_failed';
end;
$$;

