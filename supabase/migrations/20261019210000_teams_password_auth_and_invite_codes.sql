-- Teams, reusable one-hour invite codes, and team-aware article permissions.
-- Email/password authentication itself is provided by Supabase Auth; this migration
-- stores no passwords and sends no email.

create extension if not exists pgcrypto with schema extensions;

alter table public.app_profiles
drop constraint if exists app_profiles_name_key;

create table if not exists public.app_teams (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(trim(name)) between 1 and 80),
  owner_profile_id text not null references public.app_profiles(id) on delete cascade,
  legacy_group_id text unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.app_team_memberships (
  team_id uuid not null references public.app_teams(id) on delete cascade,
  profile_id text not null references public.app_profiles(id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key (team_id, profile_id)
);

create table if not exists public.app_team_invites (
  id uuid primary key default gen_random_uuid(),
  team_id uuid not null references public.app_teams(id) on delete cascade,
  code_hash text not null unique,
  created_by uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  revoked_at timestamptz,
  check (expires_at > created_at)
);

create unique index if not exists app_team_invites_one_active_per_team
on public.app_team_invites (team_id)
where revoked_at is null;

create index if not exists app_team_invites_hash_idx
on public.app_team_invites (code_hash);

create table if not exists public.app_team_invite_attempts (
  id bigint generated by default as identity primary key,
  auth_user_id uuid not null references auth.users(id) on delete cascade,
  attempted_at timestamptz not null default now()
);

create index if not exists app_team_invite_attempts_user_time_idx
on public.app_team_invite_attempts (auth_user_id, attempted_at desc);

alter table public.app_articles
add column if not exists team_id uuid references public.app_teams(id) on delete set null;

create index if not exists app_articles_team_id_idx on public.app_articles(team_id);
create index if not exists app_team_memberships_profile_idx on public.app_team_memberships(profile_id);

-- Every legacy teacher group becomes one default team. The legacy key remains only
-- as a compatibility bridge for existing profiles and articles.
insert into public.app_teams (name, owner_profile_id, legacy_group_id)
select
  coalesce(nullif(trim(teacher.name), ''), teacher.id),
  teacher.id,
  coalesce(teacher.teacher_group_id, teacher.id)
from public.app_profiles teacher
where teacher.role = 'teacher'
on conflict (legacy_group_id) do nothing;

insert into public.app_team_memberships (team_id, profile_id)
select team.id, profile.id
from public.app_profiles profile
join public.app_teams team
  on team.legacy_group_id = profile.teacher_group_id
on conflict (team_id, profile_id) do nothing;

insert into public.app_team_memberships (team_id, profile_id)
select team.id, team.owner_profile_id
from public.app_teams team
on conflict (team_id, profile_id) do nothing;

alter table public.app_articles disable trigger app_guard_article_workflow_trigger;

update public.app_articles article
set team_id = team.id
from public.app_teams team
where article.team_id is null
  and article.teacher_group_id = team.legacy_group_id;

alter table public.app_articles enable trigger app_guard_article_workflow_trigger;

