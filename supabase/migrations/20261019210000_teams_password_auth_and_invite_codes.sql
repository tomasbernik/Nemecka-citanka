create or replace function public.app_guard_article_workflow()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  publisher boolean := public.app_is_publisher();
  teacher_can_approve boolean;
  content_changed boolean := false;
  requested_approval_changed boolean := false;
  requested_publication_changed boolean := false;
begin
  if new.visibility <> 'public' then
    raise exception 'All articles must be public';
  end if;

  if new.team_id is not null
     and not publisher
     and not public.app_is_team_member(new.team_id, new.owner_profile_id) then
    raise exception 'article_owner_must_be_team_member';
  end if;

  if tg_op = 'INSERT' then
    if not publisher then
      new.published := false;
      if new.approval_status not in ('draft', 'pending') then
        new.approval_status := 'pending';
      end if;
    end if;
    return new;
  end if;

  teacher_can_approve := public.app_can_moderate_article(old.team_id, old.teacher_group_id);

  if new.owner_profile_id is distinct from old.owner_profile_id and not publisher then
    raise exception 'Only the publisher can change article ownership';
  end if;

  if new.team_id is distinct from old.team_id
     and not publisher
     and not public.app_is_article_owner(old.owner_profile_id) then
    raise exception 'Only the article owner can choose its team';
  end if;

  if new.teacher_group_id is distinct from old.teacher_group_id and not publisher then
    raise exception 'Only the publisher can change legacy article ownership';
  end if;

  requested_approval_changed := new.approval_status is distinct from old.approval_status;
  if requested_approval_changed and not publisher and not teacher_can_approve then
    raise exception 'Only the team teacher can approve this article';
  end if;
  if requested_approval_changed then
    new.published := (new.approval_status = 'approved');
  end if;

  requested_publication_changed := new.published is distinct from old.published;
  if requested_publication_changed
     and not publisher
     and not (requested_approval_changed and teacher_can_approve) then
    raise exception 'Only the publisher can change publication';
  end if;

  content_changed :=
    new.team_id is distinct from old.team_id
    or new.title is distinct from old.title
    or new.language is distinct from old.language
    or new.variant_group_id is distinct from old.variant_group_id
    or new.level is distinct from old.level
    or new.category is distinct from old.category
    or new.category_labels is distinct from old.category_labels
    or new.summary is distinct from old.summary
    or new.text is distinct from old.text
    or new.vocabulary is distinct from old.vocabulary
    or new.inline_vocabulary is distinct from old.inline_vocabulary
    or new.image is distinct from old.image
    or new.questions is distinct from old.questions;

  if content_changed
     and not publisher
     and not public.app_is_article_owner(old.owner_profile_id) then
    raise exception 'Only the article owner can change article content';
  end if;

  if content_changed and not publisher then
    new.approval_status := 'pending';
    new.published := false;
  end if;
  if new.approval_status <> 'approved' then
    new.published := false;
  end if;
  return new;
end;
$$;

drop policy if exists "app_articles_select" on public.app_articles;
drop policy if exists "app_articles_insert" on public.app_articles;
drop policy if exists "app_articles_update" on public.app_articles;
create policy "app_articles_select"
on public.app_articles for select to anon, authenticated
using (
  (published = true and approval_status = 'approved' and visibility = 'public')
  or public.app_is_publisher()
  or public.app_is_article_owner(owner_profile_id)
  or public.app_can_moderate_article(team_id, teacher_group_id)
);
create policy "app_articles_insert"
on public.app_articles for insert to authenticated
with check (
  visibility = 'public'
  and published = false
  and public.app_is_article_owner(owner_profile_id)
  and (team_id is null or public.app_is_team_member(team_id, owner_profile_id))
);
create policy "app_articles_update"
on public.app_articles for update to authenticated
using (
  public.app_is_publisher()
  or public.app_is_article_owner(owner_profile_id)
  or public.app_can_moderate_article(team_id, teacher_group_id)
)
with check (
  visibility = 'public'
  and (
    public.app_is_publisher()
    or public.app_is_article_owner(owner_profile_id)
    or public.app_can_moderate_article(team_id, teacher_group_id)
  )
);

create or replace function public.app_manageable_articles()
returns setof public.app_articles
language sql
stable
security invoker
set search_path = public, auth
as $$
  select article.*
  from public.app_articles article
  where public.app_is_publisher()
    or public.app_is_article_owner(article.owner_profile_id)
    or public.app_can_moderate_article(article.team_id, article.teacher_group_id)
  order by article.updated_at desc, article.title asc;
$$;

create or replace function public.app_set_article_approval(target_article_id text, target_status text)
returns setof public.app_articles
language plpgsql
security invoker
set search_path = public, auth
as $$
begin
  if target_status not in ('approved', 'rejected') then
    raise exception 'Invalid approval status';
  end if;
  return query
  update public.app_articles
  set approval_status = target_status, updated_at = now()
  where id = target_article_id
    and public.app_can_moderate_article(team_id, teacher_group_id)
  returning *;
end;
$$;
