-- PINs are no longer an authentication method. A legacy student profile can be
-- claimed only by an already email-verified Supabase user, after which the
-- frontend requires the user to set a password.

drop function if exists public.app_legacy_pin_profile(text, text);

create table if not exists public.app_legacy_profile_claim_attempts (
  id bigint generated by default as identity primary key,
  auth_user_id uuid not null references auth.users(id) on delete cascade,
  attempted_at timestamptz not null default now()
);

create index if not exists app_legacy_profile_claim_attempts_user_time_idx
on public.app_legacy_profile_claim_attempts (auth_user_id, attempted_at desc);

alter table public.app_legacy_profile_claim_attempts enable row level security;
revoke all on public.app_legacy_profile_claim_attempts from anon, authenticated;

create or replace function public.app_claim_legacy_student_profile(
  target_name text,
  target_pin text
)
returns text
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  current_user_id uuid := auth.uid();
  claimed_profile_id text;
  failed_attempts integer;
begin
  if current_user_id is null then
    raise exception 'authentication_required';
  end if;

  if nullif(trim(coalesce(target_name, '')), '') is null
     or nullif(trim(coalesce(target_pin, '')), '') is null then
    return 'legacy_profile_claim_failed';
  end if;

  delete from public.app_legacy_profile_claim_attempts
  where auth_user_id = current_user_id
    and attempted_at < now() - interval '1 hour';

  select count(*)
  into failed_attempts
  from public.app_legacy_profile_claim_attempts
  where auth_user_id = current_user_id
    and attempted_at >= now() - interval '1 hour';

  if failed_attempts >= 5 then
    return 'legacy_profile_claim_temporarily_blocked';
  end if;

  select profile.id
  into claimed_profile_id
  from public.app_profiles profile
  where lower(trim(profile.name)) = lower(trim(target_name))
    and profile.pin = trim(target_pin)
    and profile.role = 'student'
    and (profile.auth_user_id is null or profile.auth_user_id = current_user_id)
  order by profile.id
  limit 1
  for update;

  if claimed_profile_id is null then
    insert into public.app_legacy_profile_claim_attempts (auth_user_id)
    values (current_user_id);
    return 'legacy_profile_claim_failed';
  end if;

  if exists (
    select 1
    from public.app_profiles profile
    where profile.auth_user_id = current_user_id
      and profile.id <> claimed_profile_id
  ) then
    insert into public.app_legacy_profile_claim_attempts (auth_user_id)
    values (current_user_id);
    return 'legacy_profile_claim_failed';
  end if;

  update public.app_profiles
  set auth_user_id = current_user_id,
      owner_auth_user_id = current_user_id,
      invite_claimed_at = coalesce(invite_claimed_at, now())
  where id = claimed_profile_id
    and (auth_user_id is null or auth_user_id = current_user_id);

  if not found then
    insert into public.app_legacy_profile_claim_attempts (auth_user_id)
    values (current_user_id);
    return 'legacy_profile_claim_failed';
  end if;

  delete from public.app_legacy_profile_claim_attempts
  where auth_user_id = current_user_id;

  return claimed_profile_id;
end;
$$;

revoke all on function public.app_claim_legacy_student_profile(text, text) from public;
grant execute on function public.app_claim_legacy_student_profile(text, text) to authenticated;

